/**
 * Writes the generated DTCG sources:
 *   src/tokens/primitives/color.json   ← definitions/palette.ts
 *   src/tokens/themes/<theme>-<mode>.json ← definitions/themes.ts
 * Hand-authored token files (space, radius, type, motion…) live beside them.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { formatHex, formatHex8, toGamut, type Oklch } from "culori";
import { C_CURVE, C_NEUTRAL, HUES, LIFT_WEIGHT, L_CHROMATIC, L_NEUTRAL, NEUTRALS, STEPS } from "./definitions/palette.ts";
import { MODES, THEMES, semantic, type SemanticTree } from "./definitions/themes.ts";
import { textTokens } from "./definitions/text.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "tokens");
const GENERATED = "Generated by scripts/generate.ts — edit scripts/definitions instead.";
const toSrgb = toGamut("rgb", "oklch");

function writeJson(path: string, data: unknown) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(data, null, 2) + "\n");
}

function swatch(l: number, c: number, h: number) {
  const oklch: Oklch = { mode: "oklch", l, c, h };
  return {
    $value: formatHex(toSrgb(oklch)),
    $extensions: { "in.brahmastra": { oklch: `oklch(${l.toFixed(3)} ${c.toFixed(3)} ${h})` } },
  };
}

function palette() {
  const color: Record<string, unknown> = { $type: "color", $description: GENERATED };

  for (const family of HUES) {
    const ramp: Record<string, unknown> = { $description: family.meaning };
    STEPS.forEach((step, i) => {
      const l = Math.min(0.985, L_CHROMATIC[i]! + family.lift * LIFT_WEIGHT[i]!);
      ramp[step] = swatch(l, family.chroma * C_CURVE[i]!, family.hue);
    });
    color[family.name] = ramp;
  }

  for (const family of NEUTRALS) {
    const ramp: Record<string, unknown> = { $description: family.meaning };
    STEPS.forEach((step, i) => {
      ramp[step] = swatch(L_NEUTRAL[i]!, family.chroma * C_NEUTRAL[i]!, family.hue);
    });
    color[family.name] = ramp;
  }

  color.white = { $value: "#ffffff" };
  // The scrim behind modals and sheets: kajal-950 at 60%.
  const ink = toSrgb({ mode: "oklch", l: L_NEUTRAL[10]!, c: NEUTRALS[0]!.chroma, h: NEUTRALS[0]!.hue });
  color.scrim = { $value: formatHex8({ ...ink, alpha: 0.6 }), $description: "Overlay behind modals and sheets." };

  return { color };
}

/** Puts `$type` on each top-level group so references stay typed. */
function typed(tree: SemanticTree) {
  const types: Record<string, string> = {
    color: "color",
    radius: "dimension",
    "border-width": "dimension",
    shadow: "shadow",
  };
  const out: Record<string, unknown> = {};
  for (const [group, value] of Object.entries(tree)) {
    out[group] = { $type: types[group], ...wrap(value) };
  }
  return out;
}

function wrap(node: unknown): Record<string, unknown> {
  if (typeof node === "string") return { $value: node };
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node as Record<string, unknown>)) out[key] = wrap(value);
  return out;
}

writeJson(join(root, "primitives", "color.json"), palette());
writeJson(join(root, "semantic", "text.json"), { $description: GENERATED, ...textTokens() });
for (const theme of THEMES) {
  for (const mode of MODES) {
    writeJson(join(root, "themes", `${theme}-${mode}.json`), {
      $description: `${GENERATED} Theme: ${theme}, mode: ${mode}.`,
      ...typed(semantic(theme, mode)),
    });
  }
}
console.log("✓ generated palette and 4 theme files");
