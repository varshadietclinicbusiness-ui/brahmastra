/**
 * Builds dist/:
 *   css/tokens.css        all variables — primitives, text styles, 4 theme × mode blocks
 *   css/typography.css    .astra-text-* classes + Indic line-height adjustments
 *   tailwind/theme.css    Tailwind v4 @theme mapping onto the variables
 *   js/tokens.js (+d.ts)  typed `vars` object of var() references
 *   figma/variables.json  Primitives + Semantic collections for Figma variables
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { TransformedToken } from "style-dictionary/types";
import { MODES, THEMES, type Mode, type ThemeName } from "./definitions/themes.ts";
import { DESKTOP_MIN_WIDTH, SCRIPT_CLASSES, TEXT_STYLES, lineHeightRatio, type ScriptClass } from "./definitions/text.ts";
import { DIST, PREFIX, SRC, baseLayer, themeLayer, type Layer } from "./lib.ts";

const HEADER = `/* Brahmāstra tokens · generated by @brahmastra/tokens — do not edit by hand. */\n`;

function write(path: string, contents: string) {
  const full = join(DIST, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, contents);
}

const block = (selector: string, body: string, scheme: Mode | null, indent = "") =>
  `${indent}${selector} {\n${scheme ? `${indent}  color-scheme: ${scheme};\n` : ""}${body
    .split("\n")
    .filter(Boolean)
    .map((line) => indent + line)
    .join("\n")}\n${indent}}\n`;

const M = `data-${PREFIX}-mode`;

async function buildCss(base: Layer, themes: Record<string, Layer>) {
  const css = [
    HEADER,
    `/* Primitives and text styles */\n`,
    block(":root", base.css, null),
    `\n/* Themes. Light is the default; set ${M}="dark" for dark, or let the OS decide. */\n`,
    block(`:root, [${M}="light"]`, themes["neutral-light"]!.css, "light"),
    block(`[${M}="dark"]`, themes["neutral-dark"]!.css, "dark"),
    `\n@media (prefers-color-scheme: dark) {\n`,
    block(`:root:not([${M}="light"])`, themes["neutral-dark"]!.css, "dark", "  "),
    `}\n`,
  ].join("");
  write("css/tokens.css", css);
}

// Load after tokens.css: these rules override the :root text variables by source order.
function buildTypography() {
  const v = (style: string, prop: string) => `var(--${PREFIX}-text-${style}-${prop})`;
  const name = (style: string, prop: string) => `--${PREFIX}-text-${style}-${prop}`;
  const styles = Object.entries(TEXT_STYLES);
  const classes = styles
    .map(
      ([style, s]) =>
        `.${PREFIX}-text-${style} {\n  font-family: ${v(style, "family")};\n  font-size: ${v(style, "size")};\n  line-height: ${v(style, "line-height")};\n  font-weight: ${v(style, "weight")};\n  letter-spacing: ${v(style, "tracking")};${style === "overline" ? "\n  text-transform: uppercase;" : ""}\n}\n`,
    )
    .join("");
  const desktop = `@media (min-width: ${DESKTOP_MIN_WIDTH}px) {\n  :root {\n${styles
    .filter(([, s]) => s.desktop[0] !== s.mobile[0] || s.desktop[1] !== s.mobile[1])
    .map(([style]) => `    ${name(style, "size")}: ${v(style, "size-desktop")};\n    ${name(style, "line-height")}: ${v(style, "line-height-desktop")};`)
    .join("\n")}\n  }\n}\n`;
  // Indian scripts: taller lines (matras and conjuncts need room) and no tracking.
  const scripts = (Object.keys(SCRIPT_CLASSES) as ScriptClass[])
    .map((cls) => {
      const sel = `:is(${SCRIPT_CLASSES[cls].map((l) => `:lang(${l})`).join(", ")})`;
      const decl = (bp: "mobile" | "desktop", pad: string) =>
        styles
          .filter(([, s]) => s.kind !== "code")
          .map(([style, s]) => `${pad}${name(style, "line-height")}: ${lineHeightRatio(s, cls, bp)};\n${pad}${name(style, "tracking")}: 0em;`)
          .join("\n");
      return `/* ${cls}: ${SCRIPT_CLASSES[cls].join(", ")} */\n${sel} {\n${decl("mobile", "  ")}\n}\n@media (min-width: ${DESKTOP_MIN_WIDTH}px) {\n  ${sel} {\n${decl("desktop", "    ")}\n  }\n}\n`;
    })
    .join("\n");
  write("css/typography.css", `${HEADER}/* Load after tokens.css. */\n${classes}\n${desktop}\n${scripts}`);
}

/** Maps a CSS token name onto Tailwind v4's theme namespaces. */
function tailwindName(token: TransformedToken): string | null {
  const [group, a, b, c] = token.path as string[];
  if (group === "color") {
    if (a === "bg") return `color-${b}`;
    if (a === "fg") return b === "default" ? "color-fg" : `color-fg-${b}`;
    if (a === "border") return b === "default" ? "color-border" : `color-border-${b}`;
    if (["accent", "success", "warning", "danger", "info"].includes(a!)) return b === "solid" ? `color-${a}` : `color-${a}-${b}`;
    if (a === "white" || a === "scrim" || a === "transparent") return `color-${a}`;
    return `color-${a}-${b}`;
  }
  if (group === "radius" && token.path.length === 2) return `radius-${a}`;
  if (group === "shadow" && ["subtle", "raised", "floating", "overlay", "modal", "drag", "up"].includes(a!)) return `shadow-${a}`;
  if (group === "shadow" && a === "inset") return "inset-shadow-well";
  if (group === "font" && a === "family") return `font-${b}`;
  if (group === "easing") return `ease-${a}`;
  if (group === "text") {
    const suffix = { size: "", "line-height": "--line-height", weight: "--font-weight", tracking: "--letter-spacing" }[b!];
    return suffix === undefined ? null : `text-${a}${suffix}`;
  }
  void c;
  return null;
}

function buildTailwind(base: Layer, theme: Layer) {
  const lines: string[] = [];
  const seen = new Set<string>();
  for (const token of [...base.tokens, ...theme.tokens]) {
    // Primitive radii are named by pixel value; only semantic radii become utilities.
    if (token.path[0] === "radius" && !theme.tokens.includes(token)) continue;
    const name = tailwindName(token);
    if (!name || seen.has(name)) continue;
    seen.add(name);
    lines.push(`  --${name}: var(--${token.name});`);
  }
  // Media queries can't read CSS variables, so breakpoints are written as literal values.
  const bp = base.tokens.filter((t) => t.path[0] === "breakpoint").map((t) => `  --breakpoint-${t.path[1]}: ${t.$value};`);
  write(
    "tailwind/theme.css",
    `${HEADER}/* Use after @import "tailwindcss"; and @import "@brahmastra/tokens/css"; */\n@theme {\n${bp.join("\n")}\n}\n@theme inline {\n${lines.join("\n")}\n}\n`,
  );
}

/** Safe areas come from the device at runtime (env()), not from tokens; the size.safe-area tokens are only for design. */
function buildSafeArea() {
  const sides = ["top", "right", "bottom", "left"];
  const vars = sides.map((s) => `  --${PREFIX}-safe-${s}: env(safe-area-inset-${s}, 0px);`).join("\n");
  const utils = sides.map((s) => `.${PREFIX}-safe-${s} { padding-${s}: var(--${PREFIX}-safe-${s}); }`).join("\n");
  write("css/safe-area.css", `${HEADER}/* Needs <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">. */\n:root {\n${vars}\n}\n${utils}\n`);
}

function buildJs(base: Layer, theme: Layer) {
  const vars: Record<string, unknown> = {};
  for (const token of [...base.tokens, ...theme.tokens]) {
    let node = vars;
    const path = token.path as string[];
    path.slice(0, -1).forEach((key) => {
      node = (node[key] ??= {}) as Record<string, unknown>;
    });
    node[path.at(-1)!] = `var(--${token.name})`;
  }
  const json = JSON.stringify(vars, null, 2);
  write("js/tokens.js", `${HEADER}export const vars = ${json};\n\nexport const themes = ${JSON.stringify(THEMES)};\nexport const modes = ${JSON.stringify(MODES)};\n`);
  write(
    "js/tokens.d.ts",
    `${HEADER}export declare const vars: ${json};\n\nexport type Theme = ${THEMES.map((t) => `"${t}"`).join(" | ")};\nexport type Mode = ${MODES.map((m) => `"${m}"`).join(" | ")};\nexport declare const themes: Theme[];\nexport declare const modes: Mode[];\n`,
  );
}

// ---------- Figma variables ----------

type Leaf = { path: string[]; type: string; value: unknown };

function leaves(node: Record<string, unknown>, path: string[] = [], inheritedType = ""): Leaf[] {
  const type = (node.$type as string) ?? inheritedType;
  if ("$value" in node) return [{ path, type, value: node.$value }];
  return Object.entries(node)
    .filter(([key]) => !key.startsWith("$"))
    .flatMap(([key, child]) => leaves(child as Record<string, unknown>, [...path, key], type));
}

const readJson = (path: string) => JSON.parse(readFileSync(path, "utf8")) as Record<string, unknown>;
const cssVar = (path: string[]) => `var(--${PREFIX}-${path.join("-")})`;

function figmaScopes(path: string[]): string[] {
  const [group, a] = path;
  if (group === "color") {
    if (a === "bg") return ["FRAME_FILL", "SHAPE_FILL"];
    if (a === "fg") return ["TEXT_FILL", "SHAPE_FILL"];
    if (a === "border") return ["STROKE_COLOR"];
    if (["accent", "success", "warning", "danger", "info"].includes(a!)) return ["ALL_FILLS", "STROKE_COLOR"];
    return ["ALL_SCOPES"];
  }
  if (group === "space") return ["GAP", "WIDTH_HEIGHT"];
  if (group === "radius") return ["CORNER_RADIUS"];
  if (group === "border-width") return ["STROKE_FLOAT"];
  if (group === "size") return ["WIDTH_HEIGHT"];
  if (group === "font" && a === "size") return ["FONT_SIZE"];
  if (group === "font" && a === "weight") return ["FONT_WEIGHT"];
  if (group === "font" && a === "family") return ["FONT_FAMILY"];
  return ["ALL_SCOPES"];
}

function figmaValue(leaf: Leaf): { type: string; value: unknown } | null {
  const v = leaf.value;
  if (typeof v === "string" && v.startsWith("{")) return { type: "ALIAS", value: v.slice(1, -1).split(".").join("/") };
  switch (leaf.type) {
    case "color":
      return { type: "COLOR", value: v };
    case "dimension": {
      const dim = v as { value: number; unit: string };
      return dim.unit === "px" ? { type: "FLOAT", value: dim.value } : null;
    }
    case "fontWeight":
    case "number":
      return leaf.path[0] === "z" ? null : { type: "FLOAT", value: v };
    case "fontFamily":
      return { type: "STRING", value: (v as string[])[0] };
    default:
      return null;
  }
}

function buildFigma() {
  const primitiveFiles = readdirSync(join(SRC, "primitives")).map((f) => join(SRC, "primitives", f));
  const primitives = primitiveFiles.flatMap((f) => leaves(readJson(f)));
  const primitiveVars = primitives.flatMap((leaf) => {
    const fv = figmaValue(leaf);
    if (!fv) return [];
    return [{ name: leaf.path.join("/"), type: fv.type, scopes: figmaScopes(leaf.path), codeSyntax: { WEB: cssVar(leaf.path) }, values: { Value: fv.value } }];
  });

  const modes = THEMES.flatMap((theme) => MODES.map((mode) => ({ theme, mode, label: cap(mode) })));
  const byName = new Map<string, { name: string; resolvedType: string; scopes: string[]; codeSyntax: object; values: Record<string, unknown> }>();
  for (const { theme, mode, label } of modes) {
    for (const leaf of leaves(readJson(join(SRC, "themes", `${theme}-${mode}.json`)))) {
      if (leaf.type === "shadow") continue; // Figma variables can't hold effects; shadows become effect styles.
      const alias = (leaf.value as string).slice(1, -1).split(".").join("/");
      const target = primitives.find((p) => p.path.join("/") === alias);
      const resolvedType = target?.type === "color" ? "COLOR" : "FLOAT";
      const name = leaf.path.join("/");
      const entry = byName.get(name) ?? { name, resolvedType, scopes: figmaScopes(leaf.path), codeSyntax: { WEB: cssVar(leaf.path) }, values: {} };
      entry.values[label] = { type: "ALIAS", value: alias };
      byName.set(name, entry);
    }
  }

  write(
    "figma/variables.json",
    JSON.stringify(
      {
        $description: "Brahmāstra variables for Figma. Semantic values alias Primitives.",
        collections: [
          { name: "Primitives", modes: ["Value"], variables: primitiveVars },
          { name: "Semantic", modes: modes.map((m) => m.label), variables: [...byName.values()] },
        ],
      },
      null,
      2,
    ) + "\n",
  );
}

const cap = (s: string) => s[0]!.toUpperCase() + s.slice(1);

// ---------- run ----------

rmSync(DIST, { recursive: true, force: true });
const base = await baseLayer();
const themes: Record<string, Layer> = {};
for (const theme of THEMES as ThemeName[]) for (const mode of MODES) themes[`${theme}-${mode}`] = await themeLayer(theme, mode);

await buildCss(base, themes);
buildTypography();
buildSafeArea();
buildTailwind(base, themes["neutral-light"]!);
buildJs(base, themes["neutral-light"]!);
buildFigma();
console.log(`✓ built ${base.tokens.length} base tokens and ${Object.keys(themes).length} theme blocks → dist/`);
