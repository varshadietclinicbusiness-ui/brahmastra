/**
 * Writes dist/styles.css (components only) and dist/brahmastra.css (tokens, type,
 * safe areas and components in one file). Component files are concatenated in
 * order, wrapped in cascade layers so any unlayered app CSS wins without !important.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const tokensDir = dirname(require.resolve("@brahmastra/tokens/css"));
const HEADER = "/* Brahmāstra UI · generated by @brahmastra/ui — edit src/css instead. */\n";

const files = readdirSync(join(root, "src/css")).filter((f) => f.endsWith(".css")).sort();
const components = files.map((f) => `/* ${f} */\n${readFileSync(join(root, "src/css", f), "utf8").trim()}\n`).join("\n");
const styles = `${HEADER}@layer astra.base, astra.components;\n\n${components}`;

const tokens = ["tokens.css", "typography.css", "safe-area.css"].map((f) => readFileSync(join(tokensDir, f), "utf8")).join("\n");
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist/styles.css"), styles);
writeFileSync(join(root, "dist/brahmastra.css"), `${tokens}\n${styles}`);
console.log(`✓ ${files.length} component stylesheets → dist/styles.css, dist/brahmastra.css`);
